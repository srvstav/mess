-- Inner and left outer joins across four tables: bookings of a student
SELECT b.meal_date, ms.name AS meal, COALESCE(m.name, '-') AS mess, b.status
FROM bookings b
JOIN students s     ON s.id = b.student_id
JOIN meal_slots ms  ON ms.id = b.slot_id
LEFT JOIN messes m  ON m.id = b.mess_id
WHERE s.phone = '7000000001'
ORDER BY b.meal_date DESC, ms.id
LIMIT 8;

-- Grouping with conditional aggregation: distribution of the previous day's bookings between the messes
SELECT ms.name AS meal,
       SUM(b.mess_id = 1)          AS bludove,
       SUM(b.mess_id = 2)          AS bluspring,
       SUM(b.status = 'skipped')   AS skipped,
       ROUND(100 * SUM(b.mess_id = 1) / SUM(b.status = 'booked'), 1) AS bludove_pct
FROM bookings b JOIN meal_slots ms ON ms.id = b.slot_id
WHERE b.meal_date = CURDATE() - INTERVAL 1 DAY
GROUP BY ms.id, ms.name
ORDER BY ms.id;

-- HAVING clause with a nested subquery: hostels with bookings above the average
SELECT h.name AS hostel, COUNT(*) AS plates_booked
FROM bookings b
JOIN students s ON s.id = b.student_id
JOIN hostels h  ON h.id = s.hostel_id
WHERE b.status = 'booked'
GROUP BY h.id, h.name
HAVING COUNT(*) > (SELECT AVG(n) FROM (SELECT COUNT(*) AS n FROM bookings b2
                   JOIN students s2 ON s2.id = b2.student_id
                   WHERE b2.status = 'booked' GROUP BY s2.hostel_id) x)
ORDER BY plates_booked DESC;

-- GROUP BY with ROLLUP: subtotals by programme and the grand total
SELECT p.code AS programme, s.year_of_study AS yr, COUNT(*) AS students
FROM students s JOIN programmes p ON p.id = s.programme_id
WHERE p.code IN ('BTECH-CSE', 'BBA')
GROUP BY p.code, s.year_of_study WITH ROLLUP;

-- Correlated subquery (NOT EXISTS): students served without a booking at that mess
SELECT s.reg_no, fn_short_name(s.full_name) AS student, ms.name AS meal, m.name AS ate_at
FROM attendance a
JOIN students s    ON s.id = a.student_id
JOIN meal_slots ms ON ms.id = a.slot_id
JOIN messes m      ON m.id = a.mess_id
WHERE NOT EXISTS (SELECT 1 FROM bookings b
                  WHERE b.student_id = a.student_id AND b.meal_date = a.meal_date
                    AND b.slot_id = a.slot_id AND b.mess_id = a.mess_id AND b.status = 'booked')
LIMIT 6;

-- Built-in string and date functions and the user-defined function fn_short_name
SELECT full_name,
       fn_short_name(full_name)               AS public_name,
       UPPER(LEFT(full_name, 1))              AS initial,
       CONCAT('+91 ', LEFT(phone, 5), ' ', RIGHT(phone, 5)) AS phone_pretty,
       TIMESTAMPDIFF(MONTH, joined_on, CURDATE()) AS months_at_muj,
       DATE_FORMAT(joined_on, '%d %b %Y')     AS joined
FROM students ORDER BY id LIMIT 5;

-- View v_daily_forecast: quantity to be prepared by each mess for the current day
SELECT meal, mess, booked, cook_for
FROM v_daily_forecast
WHERE meal_date = CURDATE()
ORDER BY slot_id, mess_id;

-- View v_meal_summary: meals served, absentees, walk-ins and surplus for donation
SELECT meal, mess, booked, cooked, served, no_shows, walk_ins, donate
FROM v_meal_summary
WHERE meal_date = CURDATE() - INTERVAL 1 DAY
ORDER BY slot_id, mess_id;

-- View v_mess_earnings: revenue, cost and profit of each mess over six days
SELECT mess,
       SUM(served)    AS plates_served,
       SUM(revenue)   AS revenue,
       SUM(food_cost) AS food_cost,
       SUM(profit)    AS profit,
       ROUND(100 * SUM(profit) / SUM(revenue), 1) AS margin_pct
FROM v_mess_earnings
WHERE meal_date BETWEEN CURDATE() - INTERVAL 6 DAY AND CURDATE() - INTERVAL 1 DAY
GROUP BY mess_id, mess;

-- View v_hostel_split: distribution of hostels between the two messes
SELECT hostel, mess, SUM(booked) AS plates
FROM v_hostel_split
WHERE meal_date = CURDATE() AND hostel IN ('B1', 'B2', 'G1', 'G2')
GROUP BY hostel_id, hostel, mess
ORDER BY hostel_id, mess;

